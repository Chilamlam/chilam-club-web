-- ============================================================
-- Chilam Club 产品反馈 - site_feedback 表
-- 在 Supabase Dashboard > SQL Editor 执行（幂等，可重复执行）
-- ============================================================
--
-- 侧栏反馈表单由 Streamlit 服务端通过 service_key 写入；游客和登录用户
-- 都能提交。浏览器不直接访问本表。
--
-- 安全与隐私：
--   1. 不保存原 IP；匿名行只保存由稳定盐和 IP 生成的 HMAC-SHA256 摘要。
--      登录用户只保存内部 user_id，不自动复制账号邮箱。
--   2. 联系方式是用户主动填写的选填字段。
--   3. 启用 RLS 且不创建 anon / authenticated 策略，只授权 service_role。
--   4. session_key 有唯一约束，同一 Streamlit 会话最多写入一条反馈。

CREATE TABLE IF NOT EXISTS public.site_feedback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    category    TEXT NOT NULL CHECK (
        category IN ('看不懂', '找不到功能', '页面报错', '数据有误', '功能建议', '其他')
    ),
    message     TEXT NOT NULL CHECK (char_length(message) BETWEEN 5 AND 1200),
    page        TEXT NOT NULL DEFAULT '',
    section     TEXT NOT NULL DEFAULT '',
    contact     TEXT,
    user_id     BIGINT,
    visitor_key TEXT,
    session_key TEXT NOT NULL CHECK (char_length(session_key) BETWEEN 1 AND 128),
    status      TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'handled')),
    handled_at  TIMESTAMPTZ,
    handled_by  TEXT
);

-- 兼容旧表。历史上没有 visitor_key 的匿名行保留 NULL，不伪造访客身份。
ALTER TABLE public.site_feedback
    ADD COLUMN IF NOT EXISTS visitor_key TEXT;

-- 只允许 NULL 或 64 位小写十六进制 HMAC 摘要。ADD CONSTRAINT 本身不幂等，
-- 因此先检查 pg_constraint；重复执行脚本不会报错。
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM pg_constraint
         WHERE conname = 'ck_site_feedback_visitor_key_format'
           AND conrelid = 'public.site_feedback'::regclass
    ) THEN
        ALTER TABLE public.site_feedback
            ADD CONSTRAINT ck_site_feedback_visitor_key_format
            CHECK (
                visitor_key IS NULL
                OR visitor_key ~ '^[0-9a-f]{64}$'
            );
    END IF;
END;
$$;

-- 一个浏览器会话只接受一条反馈。即使界面被重复点击或 rerun，也不会落两行。
CREATE UNIQUE INDEX IF NOT EXISTS uq_site_feedback_session
    ON public.site_feedback(session_key);

-- 后台默认先看未处理；分类统计也走这个索引。
CREATE INDEX IF NOT EXISTS idx_site_feedback_status_time
    ON public.site_feedback(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_site_feedback_category_time
    ON public.site_feedback(category, created_at DESC);

-- 主体时间窗索引。游客按 visitor_key，登录用户按 user_id。
CREATE INDEX IF NOT EXISTS idx_site_feedback_visitor_time
    ON public.site_feedback(visitor_key, created_at DESC)
    WHERE user_id IS NULL AND visitor_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_site_feedback_user_time
    ON public.site_feedback(user_id, created_at DESC)
    WHERE user_id IS NOT NULL;

-- 宽松的全站匿名兜底。它不能替代主体配额，只限制全站匿名洪峰。
CREATE INDEX IF NOT EXISTS idx_site_feedback_anon_time
    ON public.site_feedback(created_at DESC)
    WHERE user_id IS NULL;

-- 原子限流。所有阈值集中声明，避免魔法数字散落。
-- 不增加跨字段 CHECK：历史匿名行的 visitor_key 必须保持 NULL，若用
-- NOT VALID 约束虽能迁移，但管理员之后标记这些旧行为 handled 的 UPDATE
-- 会被重新校验并失败。主体身份因此只在 BEFORE INSERT 触发器里强制。
-- 锁顺序固定：
--   1. 游客：全站匿名锁 → visitor 锁 → COUNT → INSERT。
--   2. 登录用户：user 锁 → COUNT → INSERT。
-- 游客各主体先串行经过全站匿名锁，因此同一事务内的游客行不会反向取锁；
-- 登录分支不取匿名全站锁。PostgREST 每次反馈写入是一行，不存在跨主体
-- 批量 INSERT 的锁环。
DROP TRIGGER IF EXISTS trg_site_feedback_anonymous_rate_limit
    ON public.site_feedback;
DROP FUNCTION IF EXISTS public.enforce_site_feedback_anonymous_rate_limit();
DROP TRIGGER IF EXISTS trg_site_feedback_rate_limit
    ON public.site_feedback;

CREATE OR REPLACE FUNCTION public.enforce_site_feedback_rate_limit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    c_visitor_10m_limit CONSTANT integer := 3;
    c_visitor_24h_limit CONSTANT integer := 10;
    c_user_10m_limit CONSTANT integer := 5;
    c_user_24h_limit CONSTANT integer := 30;
    c_anon_site_10m_limit CONSTANT integer := 30;
    v_now timestamptz := clock_timestamp();
    v_recent_count bigint;
    v_daily_count bigint;
BEGIN
    IF NEW.user_id IS NOT NULL THEN
        -- 登录用户的身份始终以数据库 user_id 为准，不接受客户端 visitor_key。
        NEW.visitor_key := NULL;

        PERFORM pg_advisory_xact_lock(
            hashtextextended(
                'feedback-user:' || NEW.user_id::text,
                918273
            )
        );

        SELECT
            count(*) FILTER (
                WHERE created_at >= v_now - interval '10 minutes'
            ),
            count(*) FILTER (
                WHERE created_at >= v_now - interval '24 hours'
            )
          INTO v_recent_count, v_daily_count
          FROM public.site_feedback
         WHERE user_id = NEW.user_id
           AND created_at >= v_now - interval '24 hours';

        IF v_recent_count >= c_user_10m_limit THEN
            RAISE EXCEPTION USING
                ERRCODE = 'P0001',
                MESSAGE = 'CHILAM_FEEDBACK_USER_RATE_LIMIT_10M';
        END IF;
        IF v_daily_count >= c_user_24h_limit THEN
            RAISE EXCEPTION USING
                ERRCODE = 'P0001',
                MESSAGE = 'CHILAM_FEEDBACK_USER_RATE_LIMIT_24H';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.visitor_key IS NULL
       OR NEW.visitor_key !~ '^[0-9a-f]{64}$' THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'CHILAM_FEEDBACK_IDENTITY_UNAVAILABLE';
    END IF;

    -- 固定锁序：先全站匿名兜底，再同一访客主体。
    PERFORM pg_advisory_xact_lock(
        hashtextextended('feedback-anon-global', 918271)
    );
    PERFORM pg_advisory_xact_lock(
        hashtextextended(
            'feedback-visitor:' || NEW.visitor_key,
            918272
        )
    );

    SELECT
        count(*) FILTER (
            WHERE created_at >= v_now - interval '10 minutes'
        ),
        count(*) FILTER (
            WHERE created_at >= v_now - interval '24 hours'
        )
      INTO v_recent_count, v_daily_count
      FROM public.site_feedback
     WHERE user_id IS NULL
       AND visitor_key = NEW.visitor_key
       AND created_at >= v_now - interval '24 hours';

    IF v_recent_count >= c_visitor_10m_limit THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'CHILAM_FEEDBACK_VISITOR_RATE_LIMIT_10M';
    END IF;
    IF v_daily_count >= c_visitor_24h_limit THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'CHILAM_FEEDBACK_VISITOR_RATE_LIMIT_24H';
    END IF;

    SELECT count(*) INTO v_recent_count
      FROM public.site_feedback
     WHERE user_id IS NULL
       AND created_at >= v_now - interval '10 minutes';

    IF v_recent_count >= c_anon_site_10m_limit THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'CHILAM_FEEDBACK_ANON_SITE_RATE_LIMIT_10M';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_site_feedback_rate_limit
    BEFORE INSERT ON public.site_feedback
    FOR EACH ROW
    EXECUTE FUNCTION public.enforce_site_feedback_rate_limit();

ALTER TABLE public.site_feedback ENABLE ROW LEVEL SECURITY;

-- 显式拒绝浏览器端角色，只给服务端 service_role。
REVOKE ALL ON TABLE public.site_feedback FROM anon, authenticated;
GRANT ALL ON TABLE public.site_feedback TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.site_feedback_id_seq TO service_role;
REVOKE ALL ON FUNCTION public.enforce_site_feedback_rate_limit()
    FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.enforce_site_feedback_rate_limit()
    TO service_role;

COMMENT ON TABLE public.site_feedback IS
    '产品反馈；仅 service_role 读写，按 HMAC 访客或 user_id 原子限流';
COMMENT ON COLUMN public.site_feedback.page IS
    '提交时所在的主页面名称';
COMMENT ON COLUMN public.site_feedback.section IS
    '提交时所在的子页面或页签';
COMMENT ON COLUMN public.site_feedback.session_key IS
    '随机会话标识，用于防重复；不包含账号或浏览器指纹';
COMMENT ON COLUMN public.site_feedback.visitor_key IS
    '匿名反馈专用：稳定盐与规范化 IP 的 HMAC-SHA256；不含原 IP';

