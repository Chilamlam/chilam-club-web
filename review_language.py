def current_wording(value):
    """Return a copy with superseded generated commentary replaced."""
    if isinstance(value, dict):
        return {key: current_wording(item) for key, item in value.items()}
    if isinstance(value, list):
        return [current_wording(item) for item in value]
    if isinstance(value, str):
        # Replace generated sentences before broad label rules can expose their
        # fragments. This keeps the source phrase intact for exact matching.
        for old, new in REPLACEMENTS.items():
            if len(old) >= 20:
                value = value.replace(old, new)
        for pattern, replacement in PATTERN_REPLACEMENTS:
            value = pattern.sub(replacement, value)
        for old, new in REPLACEMENTS.items():
            value = value.replace(old, new)
    return value
